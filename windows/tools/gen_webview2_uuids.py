#!/usr/bin/env python3
"""Generates src/webview2_mingw_uuids.h from the WebView2 SDK header.

Why: MinGW's __uuidof() is a template emulation that needs one __CRT_UUID_DECL per interface, and the
Microsoft header only provides MSVC-style __declspec(uuid). MSVC builds do not use the generated file.

Usage:  python3 windows/tools/gen_webview2_uuids.py <path/to/WebView2.h> <sdk-version>
Re-run it whenever the pinned SDK version changes (see cmake/FetchWebView2.cmake).
"""
import re
import sys

header, version = sys.argv[1], sys.argv[2]
text = open(header, encoding="utf-8", errors="replace").read()
pat = re.compile(r'MIDL_INTERFACE\("([0-9a-fA-F\-]{36})"\)\s*(ICoreWebView2\w*)\s*:')
seen, out = set(), []
for guid, name in pat.findall(text):
    if name in seen:
        continue
    seen.add(name)
    p = guid.split("-")
    b = p[3] + p[4]
    bytes_ = ",".join("0x" + b[i:i + 2] for i in range(0, 16, 2))
    out.append(f"__CRT_UUID_DECL({name},0x{p[0]},0x{p[1]},0x{p[2]},{bytes_})")

with open(sys.argv[3] if len(sys.argv) > 3 else "windows/src/webview2_mingw_uuids.h", "w") as f:
    f.write(f"// GENERATED by tools/gen_webview2_uuids.py from WebView2 SDK {version}. Do not edit.\n")
    f.write("// MinGW only: lets __uuidof(ICoreWebView2...) work. MSVC gets this from WebView2.h itself.\n")
    f.write("#pragma once\n#if defined(__MINGW32__)\n")
    f.write("\n".join(out))
    f.write("\n#endif\n")
print(f"{len(out)} interfaces")
